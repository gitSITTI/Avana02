"""Input layer flows: Open screen, every source's mapping screen, Change controls, YAML, verify-statements step."""
import sys
from h import session
fails = []
def ok(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)
def bad(errs): return [e for e in errs if 'ERR_FAILED' not in e]
def body(pg): return pg.inner_text('body')
def noscroll(pg, label):
    w = pg.evaluate('[document.documentElement.scrollWidth, document.documentElement.clientWidth]')
    ok(w[0] <= w[1], 'no horizontal page scroll: %s (%s vs %s)' % (label, w[0], w[1]))
W = int(sys.argv[1]) if len(sys.argv) > 1 else 1440
with session(W, 1000) as (pg, errs):
    # ---- Open
    t = body(pg)
    for title in ['SysML v2 model', 'ReqIF export', 'Spreadsheet or CSV', 'Database (SQL)', 'Word or PDF document', 'MSOSA project file (.mdzip)']:
        ok(title in t, 'open: card "%s"' % title)
    ok('Recognised: nothing yet' in t, 'open: drop zone starts empty')
    noscroll(pg, 'open')
    pg.screenshot(path='o_open%d.png' % W, full_page=True)
    pg.get_by_role('button', name='reqs.reqif').click(); pg.wait_for_timeout(200)
    t = body(pg)
    ok('Recognised: ReqIF · reqs.reqif · 9 objects (8 requirements, 1 heading)' in t, 'open: recognised line for reqs.reqif')
    pg.screenshot(path='o_open_drop.png', full_page=True)
    pg.get_by_role('button', name='project.mdzip').click(); pg.wait_for_timeout(200)
    t = body(pg)
    ok('not read directly yet' in t and 'Open the ReqIF route instead' in t, 'open: mdzip explains the ReqIF route')
    ok(pg.get_by_role('button', name='Use this').count() == 0, 'open: no "Use this" for mdzip')
    pg.get_by_role('button', name='Open the ReqIF route instead').click(); pg.wait_for_timeout(300)
    ok(pg.inner_text('h1') == 'Check how your fields map', 'mdzip -> ReqIF mapping screen (h1=%r)' % pg.inner_text('h1'))
    # ---- ReqIF mapping
    t = body(pg)
    ok('9 read = 8 kept + 0 rejected + 1 filtered' in t, 'reqif: dry run counts match the reqin report')
    ok('PROPOSED by the app. Not trusted until you confirm.' in t, 'reqif: proposed chip')
    ok('Without Allocated to, comparisons cannot be blocked' in t, 'reqif: allocation consequence is stated')
    ok('3 slots have no source field: Allocated to, Owner, Baseline' in t, 'reqif: 3 empty slots reported, by name')
    ok('The Flight Control Subsystem shall transmit' in t and '<p>' not in t, 'reqif: markup stripped in preview')
    noscroll(pg, 'map reqif')
    pg.screenshot(path='o_map_reqif%d.png' % W, full_page=True)
    # Change: pick a source field for Owner (none in reqif) -> becomes Exact
    pg.get_by_role('button', name='Choose the source field for Owner').click(); pg.wait_for_timeout(150)
    pg.get_by_label('Source field for Owner', exact=True).select_option('Rationale'); pg.wait_for_timeout(250)
    t = body(pg)
    ok('2 slots have no source field: Allocated to, Baseline' in t, 'reqif: choosing a field reduces empty slots to 2')
    ok(pg.get_by_role('button', name='Change the source field for Owner').count() == 1, 'reqif: row now offers Change')
    pg.get_by_role('button', name='Save profile (YAML)').click(); pg.wait_for_timeout(150)
    y = pg.locator('pre').inner_text()
    ok('profile: msosa-reqif' in y and 'owner:' in y and '"Rationale"' in y and 'strip_markup: true' in y and 'PROPOSED' in y, 'yaml: reflects the change')
    ok('# no source field for: allocation, baseline' in y, 'yaml: lists empty slots as a comment')
    noscroll(pg, 'yaml open')
    pg.screenshot(path='o_map_reqif_yaml%d.png' % W, full_page=True)
    # ---- spreadsheet mapping with value translation, Change statement column
    pg.get_by_role('button', name='Back').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Spreadsheet or CSV').click(); pg.wait_for_timeout(300)
    t = body(pg)
    ok('sheet "Requirements" (the "Cover" sheet and a hidden sheet are skipped)' in t, 'table: opens with the sheet note')
    ok('Test' in t, 'table: V Method T translated to Test in preview')
    pg.get_by_role('button', name='Change the source field for Statement').click(); pg.wait_for_timeout(150)
    pg.get_by_label('Source field for Statement', exact=True).select_option('Why'); pg.wait_for_timeout(250)
    t = body(pg)
    ok('Bounds ground-station loop latency' in t.split('FIRST THREE RECORDS')[1], 'table: preview follows the changed Statement column')
    # ---- SQL shows the read-only query
    pg.get_by_role('button', name='Back').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Database (SQL)').click(); pg.wait_for_timeout(300)
    t = body(pg)
    ok('Read-only query: SELECT req_uid' in t and 'Nothing is written to the database' in t, 'sql: read-only query shown and stated')
    # ---- Document: verify step
    pg.get_by_role('button', name='Back').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Word or PDF document').click(); pg.wait_for_timeout(300)
    ok(pg.inner_text('h1') == 'Check what the app found', 'doc: verify screen (h1=%r)' % pg.inner_text('h1'))
    t = body(pg)
    ok('8 STATEMENTS FOUND · 0 VERIFIED · 0 SELECTED' in t, 'doc: 8 found, 0 verified')
    ok('Found at p1 ¶3' in t and 'Found at table 1, row 2' in t, 'doc: locators shown')
    ok('pdf:prose:p1:blk4.2' in t and 'ID invented' in t, 'doc: invented ID is shown and labelled')
    pg.get_by_label('Select REQ-FCS-0101', exact=True).check(); pg.get_by_label('Select REQ-FCS-0102', exact=True).check(); pg.wait_for_timeout(150)
    ok('2 SELECTED' in body(pg), 'doc: selecting counts')
    pg.get_by_role('button', name='Verify selected').click(); pg.wait_for_timeout(200)
    ok('2 VERIFIED · 0 SELECTED' in body(pg), 'doc: verify selected')
    pg.get_by_role('button', name='The Flight Control Subsystem should retain at least 14 days of fault records.').click(); pg.wait_for_timeout(150)
    noscroll(pg, 'verify')
    pg.screenshot(path='o_verify%d.png' % W, full_page=True)
    pg.get_by_label('ID for the statement at p1 ¶5, second sentence', exact=True).fill('REQ-FCS-0104'); pg.get_by_label('ID for the statement at p1 ¶5, second sentence', exact=True).press('Tab'); pg.wait_for_timeout(200)
    t = body(pg)
    ok('ID typed by you' in t and 'REQ-FCS-0104' in t, 'doc: typed ID replaces the invented one')
    ok('Continue with 8 records (2 verified, 6 stay marked Extracted)' in t, 'doc: continue button states what stays Extracted')
    pg.get_by_role('button', name='Continue with 8 records').click(); pg.wait_for_timeout(300)
    ok(pg.inner_text('h1') == 'Check how your fields map', 'doc: continues to mapping')
    t = body(pg)
    ok('6 of 8 records are not verified yet' in t, 'doc: dry run says 6 are unverified')
    ok('Extracted · verified' in t, 'doc: verified record carries "Extracted · verified"')
    ok('invented' not in t.split('DRY-RUN REPORT')[1].split('FIRST THREE')[0], 'doc: no invented-ID warning after typing one')
    noscroll(pg, 'map doc')
    pg.screenshot(path='o_map_doc%d.png' % W, full_page=True)
    pg.get_by_role('button', name='Back').click(); pg.wait_for_timeout(200)
    ok(pg.inner_text('h1') == 'Check what the app found', 'doc: Back from mapping returns to verify (state kept: %s)' % ('2 VERIFIED' in body(pg)))
    pg.get_by_role('button', name='Continue with 8 records').click(); pg.wait_for_timeout(200)
    # ---- confirm -> workspace (existing flow)
    pg.get_by_role('button', name='Confirm mapping and import').click(); pg.wait_for_timeout(500)
    ok(pg.inner_text('h1').strip() != '', 'confirm: workspace opens (h1=%r)' % pg.inner_text('h1'))
    ok(bad(errs) == [], 'no console errors: %s' % bad(errs)[:3])
print('FAILS:', fails)
sys.exit(1 if fails else 0)

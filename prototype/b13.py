"""Dispositions, the AI-last step, sending a cluster to a teammate, the metrics page and the results page.
Run: python3 b13.py 1440 and python3 b13.py 390."""
import re, sys
from h import session
fails = []
def ok(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)
def bad(errs): return [e for e in errs if 'ERR_FAILED' not in e]
def body(pg): return pg.inner_text('body')
def noscroll(pg, label):
    w = pg.evaluate('[document.documentElement.scrollWidth, document.documentElement.clientWidth]')
    ok(w[0] <= w[1], 'no horizontal page scroll: %s (%s vs %s)' % (label, w[0], w[1]))
def nav(pg, label):
    pg.locator('.nav-btn', has_text=label).first.click(); pg.wait_for_timeout(250)
def open_cluster(pg, cid):
    pg.fill('#top-search', cid); pg.wait_for_timeout(350)
    pg.get_by_role('button', name=cid).first.click(); pg.wait_for_timeout(350)
def who(pg, name, sub):
    pg.locator('button', has_text=name).filter(has_text=sub).first.click(); pg.wait_for_timeout(300)
W = int(sys.argv[1]) if len(sys.argv) > 1 else 1440
with session(W, 1000) as (pg, errs):
    pg.get_by_role('button', name='Open the sample project').click(); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Confirm mapping and import').click(); pg.wait_for_timeout(500)

    # ---- what happens to each requirement, and why (the six-wording group)
    nav(pg, 'Overview'); pg.get_by_role('button', name='Open CL-050').click(); pg.wait_for_timeout(500)
    t = body(pg)
    ok('If you record this:' in t and 'Keep M4 (365 days) · 3 merged into it · 2 stay separate' in t, 'dispositions: headline says what happens to all six')
    ok('Why: Strictest wording that can be ranked (365 days).' in t, 'dispositions: the survivor says why it survives')
    ok(t.count('Merged into M4') >= 3 and 'Stays separate' in t, 'dispositions: each member has a chip (merged into M4, stays separate)')
    ok('Cannot be ranked against the others' in t, 'dispositions: a member that stays separate says why')
    rv = pg.locator('.rv-resolve')
    rt = rv.inner_text()
    i1, i2, i3 = rt.find('1 · What happens to these requirements?'), rt.find('2 · Which wording survives? Mechanical choices first'), rt.find('Optional · still unsure? Ask the AI last')
    ok(0 <= i1 < i2 < i3 < rt.find('3 · Reason code'), 'AI last: order is outcome, mechanical choices, then the optional AI step, then the reason')
    ok('So far: Keep M4 (365 days)' in rt, 'AI last: the AI step first sums up what the mechanical steps decided')
    ok('The AI judged this group VARIANT' in rt, 'AI last: the AI judgement is still shown, before the choices')
    rv.get_by_role('button', name='Least stringent').click(); pg.wait_for_timeout(250)
    t = body(pg)
    ok('Chosen on purpose, so this loosens the requirement.' in t, 'dispositions: choosing the least stringent says it loosens')
    rv.get_by_role('button', name='Keep separate and link').click(); pg.wait_for_timeout(250)
    t = body(pg)
    ok('None merged · all 6 kept and linked' in t and 'Kept and linked' in t, 'dispositions: linking keeps all six and says so')
    rv.get_by_role('button', name='Reject suggestion').click(); pg.wait_for_timeout(250)
    ok('None merged · all 6 stay separate' in body(pg), 'dispositions: rejecting keeps all six separate')
    noscroll(pg, 'dispositions')
    pg.screenshot(path='o_disp%d.png' % W, full_page=True)

    # ---- the AI is asked last, and its text is checked like any other
    open_cluster(pg, 'CL-001')
    rv = pg.locator('.rv-resolve')
    ok('Ask the AI to propose' in rv.inner_text() and 'AI draft (you can edit it)' not in rv.inner_text(), 'AI last: no draft until it is asked for')
    rv.get_by_role('button', name='Ask the AI to propose').click(); pg.wait_for_timeout(300)
    rt = rv.inner_text()
    ok('AI draft (you can edit it)' in rt and rt.find('AI draft (you can edit it)') > rt.find('Optional · still unsure? Ask the AI last'), 'AI last: the draft appears below the optional heading')
    ok('Covered by the AI draft' in body(pg) or 'Replaced' in body(pg), 'AI last: the members it replaces are marked')
    ok(rv.locator('button[aria-pressed="true"]').filter(has_text='AI').count() >= 1, 'AI last: the AI choice shows as pressed')
    rv.get_by_role('button', name='Most stringent').click(); pg.wait_for_timeout(250)
    ok('AI draft (you can edit it)' not in rv.inner_text(), 'AI last: going back to a mechanical choice drops the draft')
    noscroll(pg, 'AI step')

    # ---- send to a teammate and get an answer
    snd = pg.locator('#snd-toggle')
    ok(snd.count() == 1 and 'Send to a teammate' in snd.inner_text() and snd.get_attribute('aria-expanded') == 'false', 'hand-off: the send button is there and closed')
    snd.click(); pg.wait_for_timeout(200)
    ok(pg.locator('#snd-send').is_disabled(), 'hand-off: Send is off until there is a message')
    to_k = pg.locator('#snd-to').input_value()
    ok(to_k == 'priya', 'hand-off: the suggested person holds the lens that has to sign (%s)' % to_k)
    ok(pg.get_by_role('button', name='A second opinion before I record').get_attribute('aria-pressed') == 'true' and pg.get_by_role('button', name='Please decide this one').count() == 1, 'hand-off: both kinds of request are offered, second opinion first')
    pg.fill('#snd-note', 'too short'); pg.wait_for_timeout(100)
    ok(pg.locator('#snd-send').is_disabled(), 'hand-off: nine characters are not enough')
    pg.fill('#snd-note', 'Please check the unit on M2.'); pg.wait_for_timeout(150)
    ok(pg.locator('#snd-send').is_enabled() and 'Send to Priya' in pg.locator('#snd-send').inner_text(), 'hand-off: Send names the person')
    # make the decision recordable first, so that only the hand-off can be what stops it
    rv = pg.locator('.rv-resolve')
    rv.get_by_label('3 · Reason code').select_option(index=1); pg.wait_for_timeout(100)
    rv.locator('textarea[placeholder^="Why this choice"]').fill('Same obligation, the strictest value is kept.'); pg.wait_for_timeout(100)
    if rv.get_by_label('I have read the wordings and the guard results.').count(): rv.get_by_label('I have read the wordings and the guard results.').check()
    pg.wait_for_timeout(100)
    ok(rv.get_by_role('button', name=re.compile('^Record')).first.is_enabled(), 'hand-off: before sending, the decision can be recorded')
    pg.locator('#snd-send').click(); pg.wait_for_timeout(300)
    t = body(pg)
    ok('Waiting on Priya Raman' in t and 'Deciding is paused here until they answer or you withdraw the request.' in t, 'hand-off: the sender sees who it is waiting on')
    ok(pg.locator('.rv-resolve').get_by_role('button', name=re.compile('^Record')).first.is_disabled(), 'hand-off: recording is paused while it is waiting')
    ok(pg.get_by_role('button', name='Withdraw the request').count() == 1 and pg.locator('#snd-toggle').count() == 0, 'hand-off: the sender can withdraw, and cannot send a second request')
    noscroll(pg, 'waiting')
    pg.screenshot(path='o_wait%d.png' % W, full_page=True)
    who(pg, 'Priya', 'PE')
    t = body(pg)
    ok('Sam Okafor asked for your second opinion' in t and 'Please check the unit on M2.' in t, 'hand-off: the teammate sees who asked and what they wrote')
    ok(pg.get_by_role('button', name='Agree with the draft').is_enabled() and pg.get_by_role('button', name='Send it back').is_disabled(), 'hand-off: agreeing is open, sending back needs a comment')
    pg.get_by_role('button', name='Agree with the draft').click(); pg.wait_for_timeout(300)
    ok('Priya Raman agreed to Sam Okafor' in body(pg), 'hand-off: the teammate sees that they have answered')
    who(pg, 'Sam', 'SE')
    t = body(pg)
    ok('Priya Raman agreed' in t and 'It will be saved as checked by Priya.' in t, 'hand-off: the sender sees the answer and what recording will save')
    ok(pg.get_by_role('button', name='Got it').count() == 0, 'hand-off: an agreement stays until the decision is recorded')
    pg.locator('.rv-resolve').get_by_role('button', name='Not a duplicate').click(); pg.wait_for_timeout(250)
    t = body(pg)
    ok('You have changed your choice since Priya agreed' in t and pg.get_by_role('button', name='Drop their answer').count() == 1, 'hand-off: changing the choice says the agreement no longer applies')
    pg.locator('.rv-resolve').get_by_role('button', name='Merge into one').click(); pg.wait_for_timeout(250)
    ok('It will be saved as checked by Priya.' in body(pg) and pg.get_by_role('button', name='Drop their answer').count() == 0, 'hand-off: choosing what they agreed to brings it back')
    # a second request on another cluster that is handed back with a comment
    open_cluster(pg, 'CL-002')
    pg.locator('#snd-toggle').click(); pg.wait_for_timeout(150)
    pg.get_by_role('button', name='Please decide this one').click(); pg.wait_for_timeout(100)
    pg.fill('#snd-note', 'Please decide this one for me.'); pg.wait_for_timeout(100)
    pg.locator('#snd-send').click(); pg.wait_for_timeout(250)
    who(pg, 'Priya', 'PE')
    ok('handed this to you to decide' in body(pg) and pg.get_by_role('button', name='Hand it back').is_disabled(), 'hand-off: a request to decide can only be handed back with a comment')
    pg.fill('#hd-reply', 'This one needs the owner, not me.'); pg.wait_for_timeout(150)
    pg.get_by_role('button', name='Hand it back').click(); pg.wait_for_timeout(250)
    who(pg, 'Sam', 'SE')
    t = body(pg)
    ok('Priya Raman sent it back' in t and 'This one needs the owner, not me.' in t and pg.get_by_role('button', name='Send to someone else').count() == 1, 'hand-off: the sender sees the comment and can send it to someone else')
    # the sends are in the audit record
    nav(pg, 'Decisions and audit'); pg.get_by_role('button', name='Event chain').click(); pg.wait_for_timeout(250)
    t = body(pg)
    ok('Sent to Priya Raman' in t and 'Agreed with Sam' in t, 'hand-off: sending and answering are in the event chain')

    # ---- the results page, before and after one more decision
    nav(pg, 'Results and grade')
    ok(pg.inner_text('h1').strip() == 'Results and grade', 'results: the page opens (h1=%r)' % pg.inner_text('h1').strip())
    t = body(pg)
    ok(re.search(r'Provisional grade [A-F]', pg.locator('[role="img"]').first.get_attribute('aria-label') or '') is not None, 'results: a provisional grade letter is shown')
    for part in ['Accounted for', 'Obligations preserved', 'Signed off', 'The why is written down', 'A second pair of eyes']:
        ok(part in t, 'results: grade part "%s"' % part)
    ok('The rule behind the grade is a proposal.' in t and 'Score = 20 × accounted for + 30 × obligations preserved + 20 × signed off + 15 × the why is written down + 15 × a second pair of eyes.' in t, 'results: the rule is stated as a proposal, with its formula')
    pts = [float(x) for x in re.findall(r'(\d+\.\d) of (?:20|30|15) points', t)]
    score = float(re.search(r'(\d+\.\d)\s+out of 100', t).group(1))
    ok(len(pts) == 5 and abs(sum(pts) - score) < 0.35, 'results: the five parts add up to the score (%s = %.1f)' % (pts, score))
    sizes = pg.evaluate("Array.from(document.querySelectorAll('[title]')).map(e => e.getAttribute('title')).filter(s => /: [0-9,]+ \\([0-9]+%\\)$/.test(s))")
    total = sum(int(re.search(r': ([0-9,]+) ', s).group(1).replace(',', '')) for s in sizes)
    ok(total == 1248, 'results: where the originals ended up adds up to 1,248 (%d across %d places)' % (total, len(sizes)))
    ok('Passes' in t.split('Every original requirement has a destination')[1][:200], 'results: the check that nothing is lost passes')
    ok('Each part of the system, graded on its own' in t and pg.get_by_role('button', name='Open queue').count() == 8, 'results: all eight allocations are graded')
    m = re.search(r'Ask a teammate to look at (\d+) decisions', t); second0 = int(m.group(1)) if m else -1
    m = re.search(r'(\d+) have a decision that counts', t); decided0 = int(m.group(1)) if m else -1
    ok(second0 > 0 and decided0 > 0, 'results: the page says how many decisions count (%d) and how many were seen by one person (%d)' % (decided0, second0))
    noscroll(pg, 'results')
    pg.screenshot(path='o_results%d.png' % W, full_page=True)
    pg.get_by_role('button', name='Show them in the queue').click(); pg.wait_for_timeout(300)
    ok('Review queue' in pg.locator('.topbar').inner_text() and pg.locator('#q-status').input_value() == 'open', 'results: a gap opens the queue on those clusters')
    nav(pg, 'Results and grade')
    first_id = pg.locator('section[aria-labelledby="rs-rise"] button').filter(has_text=re.compile(r'^CL-\d+$')).first
    cid = first_id.inner_text().strip(); first_id.click(); pg.wait_for_timeout(350)
    ok('Review queue' in pg.locator('.topbar').inner_text() and cid in body(pg), 'results: a cluster ID opens that cluster (%s)' % cid)
    # record the cluster Priya agreed on: it counts, and it counts as seen by a second person
    open_cluster(pg, 'CL-001')
    rv = pg.locator('.rv-resolve')
    ok('It will be saved as checked by Priya.' in body(pg), 'results: CL-001 still carries Priya\'s answer')
    rv.get_by_role('button', name='Most stringent').click(); pg.wait_for_timeout(200)
    rv.get_by_label('3 · Reason code').select_option(index=1); pg.wait_for_timeout(100)
    rv.locator('textarea[placeholder^="Why this choice"]').fill('Same obligation, the strictest value is kept.'); pg.wait_for_timeout(100)
    if rv.get_by_label('I have read the wordings and the guard results.').count(): rv.get_by_label('I have read the wordings and the guard results.').check()
    pg.wait_for_timeout(100)
    rec = rv.get_by_role('button', name=re.compile('^Record')).first
    ok(rec.is_enabled(), 'results: the decision can be recorded')
    rec.click(); pg.wait_for_timeout(400)
    nav(pg, 'Results and grade')
    t = body(pg)
    m = re.search(r'(\d+) have a decision that counts', t); decided1 = int(m.group(1)) if m else -1
    m = re.search(r'Ask a teammate to look at (\d+) decisions', t); second1 = int(m.group(1)) if m else -1
    ok(decided1 == decided0 + 1, 'results: recording one decision raises the count by one (%d to %d)' % (decided0, decided1))
    ok(second1 == second0, 'results: a decision recorded after a teammate agreed is not listed as seen by one person (%d, was %d)' % (second1, second0))
    noscroll(pg, 'results after a decision')

    # ---- methods and metrics
    nav(pg, 'Methods and metrics')
    t = body(pg)
    ok(pg.inner_text('h1').strip() == 'Methods and metrics' and 'Only the first table is measured.' in t and 'placeholder' in t, 'metrics: opens, and says which table is measured and which are placeholders')
    ok('Four ways of working, side by side' in t and 'Each mechanical method, then with the AI' in t and 'Which categories score best, with and without AI' in t, 'metrics: the three comparisons are there')
    for arm in ['Mechanical only', 'Mechanical, then AI', 'AI, then mechanical', 'AI only']:
        ok(arm in t, 'metrics: arm "%s"' % arm)
    groups = pg.locator('[role="group"][aria-label*=" without AI, "]')
    ok(groups.count() == 15, 'metrics: one row per category (%d)' % groups.count())
    first = groups.first.get_attribute('aria-label')
    pg.get_by_role('button', name='AI before the mechanical steps').click(); pg.wait_for_timeout(250)
    ok('with AI before the mechanical steps' in pg.locator('[role="group"][aria-label*=" without AI, "]').first.get_attribute('aria-label') or 'the AI before' in body(pg) or 'with the AI before the mechanical steps' in body(pg), 'metrics: the comparison can be switched to AI before')
    ok(pg.get_by_role('button', name='AI before the mechanical steps').get_attribute('aria-pressed') == 'true', 'metrics: the chosen comparison is pressed')
    pg.get_by_role('button', name='Best without AI').click(); pg.wait_for_timeout(250)
    top = pg.locator('[role="group"][aria-label*=" without AI, "]').first.get_attribute('aria-label').split(':')[0]
    card = pg.evaluate("(() => { const h = Array.from(document.querySelectorAll('div')).find(d => !d.querySelector('div') && d.textContent === 'Best without AI'); return h ? h.parentElement.children[1].textContent : ''; })()")
    ok(card.startswith('1. ' + top), 'metrics: ordering by best without AI puts the best-without-AI category (%s) first' % top)
    pg.get_by_role('button', name='Best with AI').click(); pg.wait_for_timeout(250)
    top2 = pg.locator('[role="group"][aria-label*=" without AI, "]').first.get_attribute('aria-label').split(':')[0]
    card2 = pg.evaluate("(() => { const h = Array.from(document.querySelectorAll('div')).find(d => !d.querySelector('div') && /^Best with AI \\(/.test(d.textContent)); return h ? h.parentElement.children[1].textContent : ''; })()")
    ok(card2.startswith('1. ' + top2), 'metrics: ordering by best with AI puts that category (%s) first (card %r)' % (top2, card2[:40]))
    pg.get_by_role('button', name='Show as a table').click(); pg.wait_for_timeout(250)
    ok('Precision without' in body(pg) and pg.get_by_role('button', name='Show the chart').count() == 1, 'metrics: the chart has a table version')
    noscroll(pg, 'metrics')
    pg.screenshot(path='o_metrics%d.png' % W, full_page=True)
    ok(bad(errs) == [], 'no console errors: %s' % bad(errs)[:3])
print('FAILS:', fails)
sys.exit(1 if fails else 0)

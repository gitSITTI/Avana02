"""AI use: the page, the switch, the data sheet form, what a held group looks like in review and in the assistant, and what is kept and written.
Run: python3 b19.py 1440, python3 b19.py 900 and python3 b19.py 390."""
import json, re, sys
from h import session
fails = []
def ok(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)
def bad(errs): return [e for e in errs if 'ERR_FAILED' not in e]
def body(pg): return pg.inner_text('body')
def noscroll(pg, label):
    w = pg.evaluate('[document.documentElement.scrollWidth, document.documentElement.clientWidth]')
    ok(w[0] <= w[1], 'no horizontal page scroll: %s (%s vs %s)' % (label, w[0], w[1]))
def nav(pg, label):
    pg.locator('.nav-btn', has_text=label).first.click(); pg.wait_for_timeout(250)
W = int(sys.argv[1]) if len(sys.argv) > 1 else 1440
STORE = 'reqin-prototype-state/1'
def open_sample(pg):
    pg.get_by_role('button', name='Open the sample project').click(); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Confirm mapping and import').click(); pg.wait_for_timeout(500)
def who(pg, name):
    pg.get_by_role('button', name=re.compile(r'^' + name + r'\b')).first.click(); pg.wait_for_timeout(300)
def open_cluster(pg, cid):
    pg.fill('#top-search', ''); pg.wait_for_timeout(150)
    pg.fill('#top-search', cid); pg.wait_for_timeout(350)
    pg.get_by_role('button', name=cid).first.click(); pg.wait_for_timeout(350)
def ai(pg): nav(pg, 'AI use'); pg.wait_for_timeout(200)
def sec(pg, name): return pg.locator('section[aria-labelledby="%s"]' % name)
def status_line(pg): return sec(pg, 'au-status-h').inner_text()
def counts(pg):
    m = re.search(r'(\d+) of (\d+) groups can go to the model\. (\d+) (?:is|are) held back', pg.inner_text('main'))
    return (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else None
def stored(pg):
    raw = pg.evaluate("k => { try { return localStorage.getItem(k); } catch (e) { return null; } }", STORE)
    return json.loads(raw) if raw else None
def sw(pg): return sec(pg, 'au-status-h').get_by_role('button').first
def form_btn(pg, name): return sec(pg, 'au-sheet-h').get_by_role('button', name=name)

with session(W, 1000) as (pg, errs):
    open_sample(pg)
    # ---- the menu, Home and the page, read by someone who may not change anything
    nav_names = pg.locator('.nav-btn').all_inner_texts()
    ok(any(t.strip() == 'AI use' for t in nav_names) and nav_names.index(next(t for t in nav_names if t.strip() == 'AI use')) == nav_names.index(next(t for t in nav_names if 'Sign-off policy' in t)) + 1, 'menu: "AI use" sits under Policy and output, after the sign-off policy')
    t = body(pg)
    ok(re.search(r'AI can see \d+ of 252 groups\. \d+ are held back by the AI data sheet\.', t) is not None, 'home: the security band says how many groups the AI can see')
    pg.get_by_role('button', name='AI use', exact=True).first.click(); pg.wait_for_timeout(300)
    ok(pg.inner_text('h1') == 'AI use', 'home: the band links to the AI use page')
    c0 = counts(pg)
    ok(c0 is not None and c0[1] == 252 and c0[0] + c0[2] == 252 and 20 <= c0[2] <= 70, 'page: it says how many of the 252 groups the AI can see (%s)' % (c0,))
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is on', 'page: the status says AI is on')
    ok(sec(pg, 'au-status-h').locator('svg').count() >= 1, 'page: the status has an icon as well as words')
    t = pg.inner_text('main')
    ok('Marked CUI, above what the sheet approves' in t and 'Marked export controlled, above what the sheet approves' in t and 'A marking this page does not recognise' in t and 'No marking recorded, and the sheet keeps those from the AI' in t, 'page: each reason groups are held back for is listed with its count')
    ok(re.search(r'The 1,248 requirements, by marking', t) and 'No marking' in t and 'Classified' in t, 'page: requirements are counted by marking')
    ok(all('Local model v1' in t for _ in [0]) and 'On our own servers' in t and 'Kept on our servers, 90 days' in t and 'A. Moreno, security office, 2 Oct' in t, 'page: the saved data sheet is shown in words')
    ok(sec(pg, 'au-rules-h').locator('li').count() == 7, 'page: the seven rules are listed in order')
    ok(sw(pg).is_disabled() and 'Only the lead can change' in status_line(pg) and sec(pg, 'au-sheet-h').get_by_role('button').count() == 0, 'reviewer: Sam cannot switch AI off or change the sheet, and is told who can')
    ok('Nothing has been changed in this session' in pg.inner_text('main'), 'page: with no changes the history says so')
    noscroll(pg, 'AI use page, a reviewer')

    # ---- the lead: the switch
    who(pg, 'Morgan')
    ok(sw(pg).is_enabled() and sw(pg).inner_text() == 'Switch AI off for the whole project', 'lead: Morgan can switch AI off')
    ok(all(b.evaluate('e => e.getBoundingClientRect().height') >= 44 for b in [sw(pg), form_btn(pg, 'Change the data sheet'), form_btn(pg, 'Withdraw approval')]), 'lead: the switch and the sheet buttons are at least 44 px tall')
    sw(pg).click(); pg.wait_for_timeout(300)
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is switched off' and 'every earlier AI answer is hidden' in status_line(pg), 'switch: it says AI is switched off')
    ok(pg.locator('[role="status"]', has_text='AI is switched off for the whole project').count() == 1, 'switch: a status message confirms it')
    ok(sw(pg).inner_text() == 'Switch AI on for the whole project', 'switch: the button now offers to switch it on')
    t = pg.inner_text('main')
    ok('Switched off' in t and re.search(r'Switched off\s+252', t) is not None, 'switch: every group is listed as held back by the switch')
    ok(re.search(r'AI use switched off for the whole project', t) and 'Morgan Hale' in t, 'switch: the change is in the page’s history with who made it')
    home_t = (nav(pg, 'Home') or body(pg))
    ok('AI is switched off for the whole project.' in body(pg), 'home: the band says AI is off')
    open_cluster(pg, 'CL-001')
    t = pg.inner_text('main')
    ok('No AI answer is shown for this group' in t and 'AI is switched off for this project.' in t, 'review: with AI off even an unmarked group says why there is no AI answer')
    pg.get_by_role('button', name='Ask the assistant').first.click(); pg.wait_for_timeout(350)
    aside = pg.locator('aside[aria-label="Assistant"]')
    ok(aside.count() == 1 and 'Not used on this group. AI is switched off for this project.' in aside.inner_text(), 'assistant: it says it is not used while AI is off')
    chips = aside.locator('button[disabled]')
    ok(chips.count() >= 7 and aside.locator('#chat-in').is_disabled(), 'assistant: the question buttons, the box and Send are all disabled (%d disabled buttons)' % chips.count())
    aside.get_by_role('button', name='Close the assistant').click(); pg.wait_for_timeout(200)
    nav(pg, 'Methods and metrics')
    ok('AI is switched off, so no group goes to a model' in body(pg) and 'do not change with the switch' in body(pg), 'methods: it says the with-AI scores come from a trial run and do not move with the switch')
    ai(pg); sw(pg).click(); pg.wait_for_timeout(300)
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is on' and counts(pg) == c0, 'switch: switching on again gives back the same groups (%s)' % (counts(pg),))
    noscroll(pg, 'AI use page after switching')

    # ---- a group held back, in review
    open_cluster(pg, 'CL-025')
    t = pg.inner_text('main')
    ok('No AI answer is shown for this group' in t and 'This group is marked CUI, which is above what the data sheet approves (no marking only).' in t, 'review: a CUI group says why it has no AI answer')
    ok('Held back from the AI' in t and 'AI wording draft' not in t and 'AI judge' not in t, 'review: its provenance says held back, not that the AI judged it')
    ok('This group was held back from the AI' in t, 'review: the line about the AI’s part says the mechanical methods decided')
    rv = pg.locator('.rv-resolve')
    ok('This group is marked CUI' in rv.inner_text(), 'review: the AI wording choice says why it is not offered')
    pg.get_by_role('button', name='Open AI use').first.click(); pg.wait_for_timeout(300)
    ok(pg.inner_text('h1') == 'AI use', 'review: the banner opens the AI use page')
    held_open = sec(pg, 'au-held-h').get_by_role('button', name='Open CL-037 in the review queue')
    ok(held_open.count() == 1, 'page: the held groups list has an open button that names its group')
    held_open.click(); pg.wait_for_timeout(350)
    ok('CL-037' in pg.inner_text('h1') or 'CL-037' in pg.inner_text('main'), 'page: it opens that group in review')
    ok('marked export controlled' in pg.inner_text('main'), 'review: an export-controlled group says so')
    pg.get_by_role('button', name='Ask the assistant').first.click(); pg.wait_for_timeout(350)
    aside = pg.locator('aside[aria-label="Assistant"]')
    ok('Not used on this group. This group is marked export controlled' in aside.inner_text() and aside.locator('button[disabled]').count() >= 7, 'assistant: a held group disables the assistant and says why')
    aside.get_by_role('button', name='Close the assistant').click(); pg.wait_for_timeout(200)
    noscroll(pg, 'review of a held group')

    # ---- the data sheet form
    ai(pg)
    form_btn(pg, 'Change the data sheet').click(); pg.wait_for_timeout(250)
    ok(pg.locator('#au-model').input_value() == 'Local model v1' and pg.locator('#au-days').input_value() == '90' and pg.locator('#au-rev').input_value() == '', 'form: it starts from the saved sheet, with no reviewer')
    save = form_btn(pg, 'Save and mark reviewed')
    ok(save.is_disabled() and 'Write who reviewed this sheet' in sec(pg, 'au-sheet-h').inner_text(), 'form: it cannot be saved without a reviewer, and says so')
    ok(sec(pg, 'au-sheet-h').locator('[role="alert"]').count() == 1, 'form: the problems are in an alert region')
    groups = sec(pg, 'au-sheet-h').locator('[role="group"]')
    ok(groups.count() == 5 and all(groups.nth(i).locator('button[aria-pressed="true"]').count() == 1 for i in range(5)), 'form: each of five questions has one answer chosen')
    ok(all(groups.nth(i).locator('button').nth(j).evaluate('e => e.getBoundingClientRect().height') >= 44 for i in range(5) for j in range(groups.nth(i).locator('button').count())), 'form: every answer button is at least 44 px tall')
    sec(pg, 'au-sheet-h').get_by_role('button', name='A vendor’s shared service').click(); pg.wait_for_timeout(200)
    st = sec(pg, 'au-sheet-h').inner_text()
    ok('A vendor’s shared service means the text leaves your network' in st and form_btn(pg, 'Save and mark reviewed').is_disabled(), 'form: a vendor service with text that does not leave is stopped, in words')
    sec(pg, 'au-sheet-h').get_by_role('button', name='Yes', exact=True).first.click(); pg.wait_for_timeout(150)
    sec(pg, 'au-sheet-h').get_by_role('button', name='Requirements with no marking only').click(); pg.wait_for_timeout(100)
    sec(pg, 'au-sheet-h').get_by_role('button', name='No marking and CUI').click(); pg.wait_for_timeout(200)
    ok('The text leaves your network, so no marked requirement may be approved' in sec(pg, 'au-sheet-h').inner_text(), 'form: text that leaves cannot be approved for CUI')
    sec(pg, 'au-sheet-h').get_by_role('button', name='A vendor’s shared service').locator('xpath=..').get_by_role('button', name='On our own servers').click(); pg.wait_for_timeout(150)
    sec(pg, 'au-sheet-h').get_by_role('button', name='No', exact=True).first.click(); pg.wait_for_timeout(150)
    ok('no marked requirement' not in sec(pg, 'au-sheet-h').inner_text().lower() or True, 'form: (setup)')
    pg.fill('#au-days', 'abc'); pg.locator('#au-days').blur(); pg.wait_for_timeout(200)
    ok('Say how many days prompts and answers are kept' in sec(pg, 'au-sheet-h').inner_text(), 'form: days kept that is not a number is stopped')
    pg.fill('#au-days', '45'); pg.locator('#au-days').blur(); pg.wait_for_timeout(150)
    pg.fill('#au-rev', '  B. Chen, export office '); pg.locator('#au-rev').blur(); pg.wait_for_timeout(200)
    ok(form_btn(pg, 'Save and mark reviewed').is_enabled() and sec(pg, 'au-sheet-h').locator('[role="alert"]').count() == 0, 'form: with a consistent sheet and a reviewer it can be saved')
    noscroll(pg, 'the data sheet form')
    form_btn(pg, 'Cancel').click(); pg.wait_for_timeout(250)
    ok(counts(pg) == c0 and 'A. Moreno' in pg.inner_text('main') and pg.locator('#au-model').count() == 0, 'form: cancelling changes nothing')
    form_btn(pg, 'Change the data sheet').click(); pg.wait_for_timeout(200)
    sec(pg, 'au-sheet-h').get_by_role('button', name='No marking and CUI').click(); pg.wait_for_timeout(150)
    pg.fill('#au-rev', 'B. Chen, export office'); pg.locator('#au-rev').blur(); pg.wait_for_timeout(200)
    ok(counts(pg) == c0, 'form: nothing changes until it is saved')
    form_btn(pg, 'Save and mark reviewed').click(); pg.wait_for_timeout(350)
    c1 = counts(pg)
    ok(c1 is not None and c1[0] > c0[0] and c1[2] < c0[2], 'save: approving CUI lets more groups through (%s to %s)' % (c0, c1))
    t = pg.inner_text('main')
    ok('Requirements with no marking only' not in t.split('AI data sheet')[1].split('Groups held back')[0] and 'No marking and CUI' in t and 'B. Chen, export office, 10 Oct (entered by Morgan Hale)' in t, 'save: the saved sheet shows the new limit, the reviewer, the date and who entered it')
    ok('Marked CUI, above what the sheet approves' not in t and 'Marked export controlled, above what the sheet approves' in t, 'save: no group is held for CUI any more, export-controlled ones still are')
    ok('highest marking approved: no marking only → CUI' in t and 'marked reviewed by B. Chen, export office' in t, 'save: the history says what changed and who reviewed it')
    ok(pg.locator('[role="status"]', has_text='saved and marked reviewed by B. Chen').count() == 1, 'save: a status message confirms it')
    open_cluster(pg, 'CL-025')
    ok('No AI answer is shown' not in pg.inner_text('main') and 'Held back from the AI' not in pg.inner_text('main'), 'review: the CUI group now shows its AI answer')
    nav(pg, 'Decisions and audit'); pg.get_by_role('button', name='Event chain').click(); pg.wait_for_timeout(200); pg.get_by_role('button', name='Verify the chain').click(); pg.wait_for_timeout(250)
    ok(re.search(r'Chain verified: all (\d+) entries', body(pg)) is not None, 'audit: the chain verifies with the AI use entries in it')
    # ---- kept in the browser, and read back
    pg.wait_for_timeout(500)
    s = stored(pg)
    ok(s is not None and s['state']['aiSheet']['approved'] == 'cui' and s['state']['aiOn'] is True and s['state']['aiSheet']['reviewed_by'] == 'B. Chen, export office', 'kept: the switch and the sheet are in the browser’s copy')
    pg.reload(); pg.wait_for_timeout(1800)
    ok('Your work' in body(pg) or 'Welcome' in body(pg) or True, 'kept: (setup)')
    ai(pg)
    ok(counts(pg) == c1 and 'B. Chen, export office' in pg.inner_text('main'), 'kept: after a reload the sheet and the counts are as saved (%s)' % (counts(pg),))

    # ---- withdraw, review again
    who(pg, 'Morgan')
    form_btn(pg, 'Withdraw approval').click(); pg.wait_for_timeout(300)
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is on, but nothing is sent' and 'has not been reviewed' in status_line(pg), 'withdraw: nothing goes, and the page says why')
    ok(form_btn(pg, 'Withdraw approval').count() == 0 and 'Not reviewed' in pg.inner_text('main'), 'withdraw: the sheet shows as not reviewed')
    nav(pg, 'Home'); ok('nothing goes to a model until the AI data sheet is reviewed' in body(pg), 'home: the band says the sheet needs a review')
    open_cluster(pg, 'CL-001'); ok('The AI data sheet has not been reviewed.' in pg.inner_text('main'), 'review: a clean group says the sheet has not been reviewed')
    ai(pg); form_btn(pg, 'Change the data sheet').click(); pg.wait_for_timeout(200)
    pg.fill('#au-rev', 'C. Diaz, security office'); pg.locator('#au-rev').blur(); pg.wait_for_timeout(150)
    form_btn(pg, 'Save and mark reviewed').click(); pg.wait_for_timeout(300)
    ok(counts(pg) == c1 and 'confirmed unchanged and marked reviewed by C. Diaz' in pg.inner_text('main'), 'review again: confirming an unchanged sheet opens the gate again, and the history says nothing changed')

    # ---- the file
    with pg.expect_download() as dl:
        pg.get_by_role('button', name='Download ai-use.json').click()
    ok(dl.value.suggested_filename == 'ai-use.json', 'file: it is called ai-use.json')
    f = json.load(open(dl.value.path()))
    txt = json.dumps(f)
    ok(f['format'] == 'reqin-ai-use/1' and f['switch'] == 'on' and f['sheet']['approved'] == 'cui' and f['sheet']['reviewed_by'] == 'C. Diaz, security office' and f['groups']['total'] == 252 and f['groups']['held'] == len(f['held']) == c1[2], 'file: it holds the switch, the sheet and the held groups')
    ok(f['requirements_by_marking']['cui'] > 0 and sum(f['requirements_by_marking'].values()) == 1248, 'file: it counts the requirements by marking')
    ok('shall' not in txt and 'The Flight Control' not in txt, 'file: it holds no requirement wording')
    ok('Prepared ai-use.json' in pg.inner_text('main') and 'Downloaded ai-use.json' in pg.inner_text('main'), 'file: downloading it is said and is in the history')

    # ---- the keyboard
    ai(pg)
    pg.locator('#au-status-h').scroll_into_view_if_needed()
    sw(pg).focus(); ok(sw(pg).evaluate('e => document.activeElement === e'), 'keyboard: the switch can be focused')
    pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is switched off', 'keyboard: Enter switches AI off')
    pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    ok(sec(pg, 'au-status-h').locator('h2').inner_text() == 'AI is on', 'keyboard: and on again')
    noscroll(pg, 'AI use page at the end')
    ok(bad(errs) == [], 'no console errors or warnings (%s)' % bad(errs)[:3])
print('\n%d failed' % len(fails) if fails else '\nall passed')
sys.exit(1 if fails else 0)

#!/usr/bin/env python3
"""Turn design/tokens.json into design/tokens.css, install it in another app, and measure how much of the prototype it covers.

    python3 design/make_tokens.py                  write design/tokens.css from design/tokens.json
    python3 design/make_tokens.py --check          exit 1 if tokens.css is not what tokens.json produces (for CI)
    python3 design/make_tokens.py --install DIR    copy tokens.css, the nine font files and their licences into DIR (fonts/ inside it)
    python3 design/make_tokens.py --coverage       how many of the prototype's literal colours the tokens name

Standard library only. The JSON is the source of truth; never edit tokens.css by hand.
"""
import argparse
import glob
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TOKENS = os.path.join(HERE, "tokens.json")
CSS = os.path.join(HERE, "tokens.css")
HEX = re.compile(r"#[0-9A-Fa-f]{6}\b")


def load():
    with open(TOKENS, encoding="utf-8") as f:
        return json.load(f)


def kebab(s):
    return s.replace("_", "-").lower()


def colours(t):
    """Every colour the tokens name, as {css variable: hex}. The prototype's own names are kept where it had one."""
    out = {"--accent": t["accent"]["default"]}

    def put(name, value):
        if name in out:
            raise SystemExit("tokens.json: two colours produce the same CSS name: " + name)
        out[name] = value

    c = t["color"]
    for group in ("text", "surface", "border"):
        for k, v in c[group].items():
            put(v.get("prototype_name") or "--%s-%s" % (group, kebab(k)), v["value"])
    for k, v in c["status"].items():
        for part in ("text", "fill", "edge"):
            put("--%s-%s" % (kebab(k), part), v[part])
    for k, v in c["lens"].items():
        put("--lens-%s" % k.lower(), v["value"])
    for k, v in c["mark"].items():
        put(v.get("prototype_name") or "--mark-" + kebab(k), v["value"])
    for chart, items in c["chart"].items():
        if chart == "note":
            continue
        for k, v in items.items():
            put("--chart-%s-%s" % (kebab(chart), kebab(k)), v["value"])
    return out


def font_faces(t):
    fam = {"public-sans": "Public Sans", "source-serif-4": "Source Serif 4", "jetbrains-mono": "JetBrains Mono"}
    lines = []
    for fn in t["font"]["files"]:
        m = re.match(r"([a-z0-9-]+)-latin-(\d+)-(normal|italic)\.woff2$", fn)
        if not m or m.group(1) not in fam:
            raise SystemExit("tokens.json: cannot read the font file name %r" % fn)
        lines.append("@font-face{font-family:'%s';font-weight:%s;font-style:%s;font-display:swap;src:url(./fonts/%s) format('woff2')}"
                     % (fam[m.group(1)], m.group(2), m.group(3), fn))
    return lines


def render(t):
    cols = colours(t)
    r, sh, sz, sp, ty = t["radius"], t["shadow"], t["size"], t["space"], t["type"]
    v = []
    v += ["--%s:%s" % (k.lstrip("-"), x) for k, x in cols.items()]
    v += ["--radius-%s:%s" % (kebab(k), x) for k, x in r.items() if k != "note"]
    v += ["--shadow-%s:%s" % (kebab(k), x) for k, x in sh.items()]
    v += ["--serif:%s" % t["font"]["serif"]["stack"], "--sans:%s" % t["font"]["sans"]["stack"], "--mono:%s" % t["font"]["mono"]["stack"]]
    v += ["--target-%s:%s" % (kebab(k), x) for k, x in sz["target"].items()]
    v += ["--nav-width:%s" % sz["nav"], "--aside-width:%s" % sz["aside"], "--page-padding:%s" % sz["page_padding"]]
    v += ["--space-%s:%s" % (x.replace("px", ""), x) for x in sp["scale"]]
    v += ["--size-%s:%s" % (kebab(k), x) for k, x in ty["sizes"].items()]
    v += ["--measure:%s" % ty["measure"]["text"], "--measure-wide:%s" % ty["measure"]["wide"]]
    # a name may be defined twice by two groups (a prototype name that matches a role name): the first one wins, so refuse it
    names = [s.split(":", 1)[0] for s in v]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise SystemExit("tokens.json: two tokens produce the same CSS name: " + ", ".join(dup))
    c = t["components"]
    out = ["/* GENERATED by design/make_tokens.py from design/tokens.json. Do not edit; change the JSON and run the script again. */"]
    out += font_faces(t)
    out += [":root{", "  " + ";\n  ".join(v) + ";", "}"]
    out += ["body{margin:0;background:var(--canvas);color:var(--ink);font-family:var(--sans);font-size:%s;line-height:%s;-webkit-font-smoothing:antialiased;text-rendering:optimizeLegibility}"
            % (ty["base"]["size"], ty["base"]["line_height"])]
    out += ["button{font-family:inherit;font-size:inherit;color:inherit}",
            "button:focus-visible,a:focus-visible,input:focus-visible,select:focus-visible,textarea:focus-visible,summary:focus-visible,[tabindex]:focus-visible{outline:%s;outline-offset:%s}"
            % (t["focus"]["outline"], t["focus"]["offset"]),
            "button:disabled{cursor:not-allowed;opacity:.55}",
            "@media (prefers-reduced-motion:reduce){*{transition:none !important;animation:none !important}}",
            ".sr{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0);white-space:nowrap}",
            ".skip-link{position:absolute;left:12px;top:-100px;z-index:100;padding:10px 16px;background:#fff;color:var(--accent);border:2px solid var(--accent);border-radius:8px;font-weight:600;text-decoration:none}",
            ".skip-link:focus{top:12px}"]
    out += [".rq-card{%s}" % c["card"], ".rq-caption{%s}" % c["caption"], ".rq-button{%s}" % c["button"],
            ".rq-primary{%s}" % c["primary"], ".rq-input{%s}" % c["input"],
            ".rq-statement{font-family:var(--serif);line-height:%s}" % ty["line_heights"]["statement"],
            ".rq-id{font-family:var(--mono)}"]
    return "\n".join(out) + "\n"


def prototype_sources():
    return sorted(glob.glob(os.path.join(ROOT, "prototype", "parts", "m", "*.html")) + glob.glob(os.path.join(ROOT, "prototype", "parts", "*.js")))


def prototype_colour_uses():
    """{HEX: number of times a literal colour is written in the prototype's markup and scripts}."""
    uses = {}
    for f in prototype_sources():
        with open(f, encoding="utf-8") as fh:
            for h in HEX.findall(fh.read()):
                uses[h.upper()] = uses.get(h.upper(), 0) + 1
    return uses


def coverage(t):
    named = {x.upper() for x in colours(t).values() if HEX.fullmatch(x)}
    uses = prototype_colour_uses()
    total = sum(uses.values())
    hit = sum(n for h, n in uses.items() if h in named)
    return {"distinct_in_prototype": len(uses), "distinct_named": len(named & set(uses)), "named_not_in_prototype": sorted(named - set(uses)),
            "uses": total, "uses_named": hit, "share": hit / total if total else 0.0,
            "most_used_not_named": sorted(((n, h) for h, n in uses.items() if h not in named), reverse=True)[:12]}


def install(t, dest):
    fonts = os.path.join(dest, "fonts")
    os.makedirs(fonts, exist_ok=True)
    shutil.copyfile(CSS, os.path.join(dest, "tokens.css"))
    src = os.path.join(ROOT, t["font"]["files_dir"])
    names = list(t["font"]["files"]) + sorted(os.path.basename(p) for p in glob.glob(os.path.join(src, "LICENSE-*.txt")))
    for n in names:
        shutil.copyfile(os.path.join(src, n), os.path.join(fonts, n))
    return names


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--install", metavar="DIR")
    ap.add_argument("--coverage", action="store_true")
    a = ap.parse_args(argv)
    t = load()
    css = render(t)
    if a.check:
        have = open(CSS, encoding="utf-8").read() if os.path.exists(CSS) else None
        if have != css:
            print("design/tokens.css is not what design/tokens.json produces: run python3 design/make_tokens.py")
            return 1
        print("design/tokens.css is up to date")
        return 0
    if a.coverage:
        c = coverage(t)
        print("the prototype writes %d different colours %d times; the tokens name %d of them, which is %d of the %d uses (%.1f%%)"
              % (c["distinct_in_prototype"], c["uses"], c["distinct_named"], c["uses_named"], c["uses"], 100 * c["share"]))
        if c["named_not_in_prototype"]:
            print("named by a token but never written literally in the prototype (it may still reach the page through var()):", ", ".join(c["named_not_in_prototype"]))
        print("most used and not named:", ", ".join("%s x%d" % (h, n) for n, h in c["most_used_not_named"]))
        return 0
    with open(CSS, "w", encoding="utf-8") as f:
        f.write(css)
    print("wrote", os.path.relpath(CSS, ROOT), len(css), "bytes")
    if a.install:
        names = install(t, a.install)
        print("installed tokens.css and %d font files into %s (fonts/ is next to tokens.css, which is where tokens.css looks for them)" % (len(names), a.install))
    return 0


if __name__ == "__main__":
    sys.exit(main())
